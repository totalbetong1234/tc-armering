// Valgt språk: lagret valg, ellers nettleserens språk, ellers norsk
let LANG = (() => {
  try { const s = localStorage.getItem("tba:lang"); if (s && I18N[s]) return s; } catch (_) { /* ingen lagring */ }
  const n = String(navigator.language || "").toLowerCase();
  if (n.startsWith("pl")) return "pl";
  if (n.startsWith("en")) return "en";
  return "no";
})();

// Oversett nøkkel. Mangler teksten på valgt språk, brukes norsk.
function t(key, params = {}) {
  const s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.no[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m));
}
